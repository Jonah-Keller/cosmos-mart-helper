/* ---- 8 - mart_cancer_staging: the histology-confirmed outcome  [UNCONFIRMED] ------------ */
/* THIS IS THE TABLE THAT MAKES COSMOS WORTH THE EFFORT. A central reviewer objection is that
   our outcome is defined by treatment rather than by histology; in the other two data sources
   registry-confirmed grade existed for two events. Please return EVERY column, unfiltered by
