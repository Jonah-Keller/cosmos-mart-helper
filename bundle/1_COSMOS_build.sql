/* ---- 1 - the universe: BPH, the study drugs, TMZ, brain tumours ------------------------- */
DROP TABLE IF EXISTS ##ux_GBM5ARI;
SELECT DISTINCT PatientDurableKey INTO ##ux_GBM5ARI FROM (
    SELECT f.PatientDurableKey
      FROM DiagnosisEventFact f JOIN DiagnosisTerminologyDim t ON t.DiagnosisKey = f.DiagnosisKey
     WHERE f.Count > 0 AND f.StartDateKey >= 20170101
       /* PSA-screening (Z12.5 / V76.44) was a universe criterion until the SneakPeek feasibility
          counts showed it alone matched more men than BPH did; it is dropped — the PSA-anchored
          cohorts are a secondary analysis and would have doubled every table. */
       AND ((t.Type = 'ICD-10-CM' AND (t.Value LIKE 'N40%' OR t.Value LIKE 'C71%' OR t.Value LIKE 'D43%'
                                    OR t.Value LIKE 'D33%' OR t.Value LIKE 'C79.31%' OR t.Value LIKE 'C70%'))
         OR (t.Type = 'ICD-9-CM'  AND (t.Value LIKE '600%' OR t.Value LIKE '191%' OR t.Value LIKE '237.5%')))
    UNION ALL
    SELECT m.PatientDurableKey
      FROM MedicationOrderFact m JOIN MedicationCodeDim cd ON cd.MedicationKey = m.MedicationKey
     WHERE m.Count > 0 AND m.MedicationKey <> -1 AND m.StartDateKey >= 20170101
       AND cd.Type = 'RxNorm'
       AND cd.Code IN ('228790','25025','77492','17300','49276','37798','720825','8629','37776')
) u;

