/* ---- 9 - mart_source: how many organisations, and from when -----------------------------
   The documented route (COS500): PatientDim.SourceComboKey_X -> PatientSourceBridgeX -> SourceDim.
   Organisation identity is neither needed nor wanted and SourceKeys are scrambled anyway; the
   transfer-completed dates are what matter, because they decide from when a record is complete. */
DROP TABLE IF EXISTS ##mart_source_GBM5ARI;
SELECT p.patient_id,
       COUNT(DISTINCT b.SourceKey)                                   AS n_sources,
       SUM(CASE WHEN s.UseInCosmosAnalytics = 1 THEN 1 ELSE 0 END)   AS n_sources_greenlit,
       MIN(CAST(CONVERT(VARCHAR(8), s.CompletedTransferStartDate_X, 112) AS INT)) AS transfer_start_datekey,
       MAX(CAST(CONVERT(VARCHAR(8), s.CompletedTransferEndDate_X,   112) AS INT)) AS transfer_end_datekey,
       MAX(CASE WHEN s.SourceCountry <> N'United States of America' THEN 1 ELSE 0 END) AS any_non_us_source
  INTO ##mart_source_GBM5ARI
  FROM ##mart_patient_GBM5ARI p
  JOIN PatientSourceBridgeX b ON b.PatientSourceComboKey = p.source_combo_key
  JOIN SourceDim s ON s.SourceKey = b.SourceKey
 GROUP BY p.patient_id;

GO
