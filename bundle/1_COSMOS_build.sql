/* ---- 2 - mart_patient ------------------------------------------------------------------- */
DROP TABLE IF EXISTS ##mart_patient_GBM5ARI;
SELECT p.DurableKey          AS patient_id,
       p.Sex                         AS sex,
       p.FirstRace                   AS race,
       p.Ethnicity                   AS ethnicity,
       YEAR(p.BirthDate)   AS birth_year,   /* adult birth dates are 1 Jan; the year is exact */
       p.DeathDate                   AS death_date,   /* NULL when unknown or masked past the snapshot */
       p.Status                      AS status,
       p.StateOrProvinceAbbreviation AS state,        /* the finest location in EDDI; we map to census division */
       p.PrimaryRUCA_X               AS ruca,         /* 1-10 rural-urban commuting area, 99 uncoded */
       p.SviSocioeconomicPercentile2020_X AS svi,     /* CONFIRM the 2020 SVI socioeconomic column name in c00 */
       p.SourceComboKey_X            AS source_combo_key
  INTO ##mart_patient_GBM5ARI
  FROM PatientDim p
  JOIN ##ux_GBM5ARI u ON u.PatientDurableKey = p.DurableKey
 WHERE p.Sex = 'Male' AND p.IsCurrent = 1;

GO
/* ---- 3 - mart_dx: one row per patient per diagnosis code, NO code filter ---------------- */
DROP TABLE IF EXISTS ##mart_dx_GBM5ARI;
SELECT f.PatientDurableKey AS patient_id, t.Type AS code_type, t.Value AS code,
       MIN(f.StartDateKey) AS first_datekey, MAX(f.StartDateKey) AS last_datekey, COUNT(*) AS n,
       /* billing diagnoses are the most reliable type (COS500); keeping their own first date and
          count lets us run a billing-only outcome definition without a second extraction */
       MIN(CASE WHEN f.Type LIKE N'Billing%' THEN f.StartDateKey END) AS first_billing_datekey,
       SUM(CASE WHEN f.Type LIKE N'Billing%' THEN 1 ELSE 0 END)       AS n_billing,
       SUM(CASE WHEN f.Type = N'Problem List' THEN 1 ELSE 0 END)     AS n_problem_list
  INTO ##mart_dx_GBM5ARI
  FROM DiagnosisEventFact f
  JOIN ##ux_GBM5ARI u ON u.PatientDurableKey = f.PatientDurableKey
  JOIN DiagnosisTerminologyDim t ON t.DiagnosisKey = f.DiagnosisKey
 WHERE f.Count > 0 AND f.StartDateKey > 0
 GROUP BY f.PatientDurableKey, t.Type, t.Value;

GO
/* ---- 4 - mart_med: patient x drug x mode x source table --------------------------------- */
DROP TABLE IF EXISTS ##mart_med_GBM5ARI;
WITH med AS (
    /* Orders come from MedicationOrderComponentFact — one row per ordered component, so a
       mixture's ingredients are counted rather than lost (COS500: this is the core order table;
       MedicationOrderFact carries MedicationKey = -1 for mixtures). Mode lives on the order. */
    SELECT oc.PatientDurableKey, oc.MedicationKey, 'order' AS source_table, mo.Mode,
           oc.StartDateKey AS d, NULL AS days_supply, oc.Quantity AS qty
           /* CONFIRM in c00: the date and quantity column names on MedicationOrderComponentFact */
      FROM MedicationOrderComponentFact oc
      JOIN MedicationOrderFact mo ON mo.MedicationOrderKey = oc.MedicationOrderKey
     WHERE oc.Count > 0 AND oc.MedicationKey > 0 AND oc.StartDateKey > 0
    UNION ALL
    SELECT a.PatientDurableKey, a.MedicationKey, 'administration', NULL,
           a.StartDateKey, NULL, NULL
      FROM MedicationAdministrationFact a WHERE a.Count > 0 AND a.MedicationKey <> -1
    UNION ALL
    SELECT p2.PatientDurableKey, p2.MedicationKey, 'dispense', NULL,
           p2.StartDateKey, p2.DaysSupply, p2.Quantity
      /* CONFIRM the days-supply and date column names on MedicationDispenseFact in c00; this is the only
         route to the duration question a reviewer asked, so it is worth a minute */
      FROM MedicationDispenseFact p2 WHERE p2.Count > 0 AND p2.MedicationKey <> -1)
SELECT m.PatientDurableKey AS patient_id,
       cd.Code AS rxnorm_code, md.GenericName AS generic_name, md.Strength AS strength,
       m.Mode AS mode, m.source_table,
       MIN(m.d) AS first_datekey, MAX(m.d) AS last_datekey, COUNT(*) AS n,
       SUM(CAST(m.days_supply AS INT)) AS n_days_supply, SUM(CAST(m.qty AS FLOAT)) AS total_quantity
  INTO ##mart_med_GBM5ARI
  FROM med m
  JOIN ##ux_GBM5ARI u ON u.PatientDurableKey = m.PatientDurableKey
  JOIN MedicationDim md ON md.MedicationKey = m.MedicationKey
  LEFT JOIN MedicationCodeDim cd ON cd.MedicationKey = m.MedicationKey AND cd.Type = 'RxNorm'
 GROUP BY m.PatientDurableKey, cd.Code, md.GenericName, md.Strength, m.Mode, m.source_table;

GO
/* ---- 4a - mart_med_qtr: the 5-ARIs and alpha-blockers, per calendar quarter ------------- */
/* Optional but valuable: exposure intensity and duration (Reviewer 4 #7) need more than a
   first and a last date, and this is a few rows per patient. */
DROP TABLE IF EXISTS ##mart_med_qtr_GBM5ARI;
SELECT m.PatientDurableKey AS patient_id, cd.Code AS rxnorm_code,
       (m.StartDateKey / 10000) * 10000 + ((((m.StartDateKey / 100) % 100 - 1) / 3) * 3 + 1) * 100 + 1
           AS quarter_start_datekey,
       COUNT(*) AS n, SUM(CAST(m.Quantity AS FLOAT)) AS total_quantity
  INTO ##mart_med_qtr_GBM5ARI
  FROM MedicationOrderComponentFact m
  JOIN MedicationOrderFact mo ON mo.MedicationOrderKey = m.MedicationOrderKey AND mo.Mode <> N'Historical'
  JOIN ##ux_GBM5ARI u ON u.PatientDurableKey = m.PatientDurableKey
  JOIN MedicationCodeDim cd ON cd.MedicationKey = m.MedicationKey AND cd.Type = 'RxNorm'
 WHERE m.Count > 0 AND m.MedicationKey > 0 AND m.StartDateKey > 0
   AND cd.Code IN ('228790','25025','77492','17300','49276','37798','720825','8629')
 GROUP BY m.PatientDurableKey, cd.Code,
          (m.StartDateKey / 10000) * 10000 + ((((m.StartDateKey / 100) % 100 - 1) / 3) * 3 + 1) * 100 + 1;

GO
/* ---- 5 - mart_proc: patient x procedure code, NO code filter ---------------------------- */
DROP TABLE IF EXISTS ##mart_proc_GBM5ARI;
SELECT r.PatientDurableKey AS patient_id, d.CptCode AS cpt_code, d.HcpcsCode AS hcpcs_code,
       CASE WHEN d.CptCode IS NOT NULL THEN 'CPT' ELSE 'HCPCS' END AS code_set,
       MIN(r.StartDateKey) AS first_datekey, MAX(r.StartDateKey) AS last_datekey, COUNT(*) AS n
  INTO ##mart_proc_GBM5ARI
  FROM ProcedureEventFact r
  JOIN ##ux_GBM5ARI u ON u.PatientDurableKey = r.PatientDurableKey
  JOIN ProcedureDim d ON d.DurableKey = r.ProcedureDurableKey
 WHERE r.Count > 0 AND r.StartDateKey > 0
 GROUP BY r.PatientDurableKey, d.CptCode, d.HcpcsCode;

