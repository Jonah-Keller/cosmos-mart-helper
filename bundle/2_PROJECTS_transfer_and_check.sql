WITH have AS (
  SELECT LOWER(TABLE_NAME) tbl, LOWER(COLUMN_NAME) col, LOWER(DATA_TYPE) dt
    FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'dbo')
SELECT c.tbl, c.col, c.typ AS contract_type, h.dt AS actual_type,
       CASE WHEN c.required = 1 THEN 'required' ELSE 'optional' END AS need,
       CASE WHEN h.col IS NULL THEN CASE WHEN c.required = 1 THEN 'MISSING' ELSE 'absent (optional)' END
            WHEN EXISTS (SELECT 1 FROM #eq e WHERE e.typ = c.typ AND e.accepted = h.dt) THEN 'PASS'
            ELSE 'WRONG TYPE' END AS verdict
  INTO #result
  FROM #contract c LEFT JOIN have h ON h.tbl = c.tbl AND h.col = c.col;
SELECT * FROM #result ORDER BY tbl, need, col;

SELECT tbl,
       SUM(CASE WHEN verdict = 'PASS' THEN 1 ELSE 0 END) AS pass_,
       SUM(CASE WHEN verdict = 'MISSING' THEN 1 ELSE 0 END) AS missing_required,
       SUM(CASE WHEN verdict = 'WRONG TYPE' THEN 1 ELSE 0 END) AS wrong_type,
       CASE WHEN NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES t WHERE t.TABLE_SCHEMA='dbo' AND LOWER(t.TABLE_NAME) = r.tbl) THEN 'TABLE ABSENT'
            WHEN SUM(CASE WHEN verdict IN ('MISSING','WRONG TYPE') AND need='required' THEN 1 ELSE 0 END) = 0 THEN 'OK'
            ELSE 'FIX BEFORE ANALYSIS' END AS table_verdict
  FROM #result r GROUP BY tbl ORDER BY tbl;

SELECT LOWER(TABLE_NAME) tbl, LOWER(COLUMN_NAME) col, LOWER(DATA_TYPE) dt
  FROM INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA = 'dbo' AND LOWER(TABLE_NAME) LIKE 'mart[_]%'
   AND NOT EXISTS (SELECT 1 FROM #contract c WHERE c.tbl = LOWER(TABLE_NAME) AND c.col = LOWER(COLUMN_NAME))
 ORDER BY 1, 2;

DROP TABLE #contract; DROP TABLE #eq; DROP TABLE #result;



/* ============================================================================================
   STEP 5 · sizes  (paste this result into handoff/round_3_sneakpeek_counts.md)
   ============================================================================================ */

USE ProjectD237BA6;
GO
SELECT t.name AS mart, SUM(p.rows) AS rows_,
       SUM(a.total_pages) * 8 / 1024 AS reserved_mb, SUM(a.used_pages) * 8 / 1024 AS used_mb
  FROM sys.tables t
  JOIN sys.indexes i ON i.object_id = t.object_id
  JOIN sys.partitions p ON p.object_id = i.object_id AND p.index_id = i.index_id
  JOIN sys.allocation_units a ON a.container_id = p.partition_id
 WHERE t.name LIKE 'mart[_]%'
 GROUP BY t.name ORDER BY used_mb DESC;
SELECT SUM(a.used_pages) * 8 / 1024 AS total_used_mb,
       SUM(a.used_pages) * 8 / 1024 * 100 / 1024.0 AS projected_full_cosmos_gb_if_this_is_sneakpeek
  FROM sys.tables t JOIN sys.indexes i ON i.object_id = t.object_id
  JOIN sys.partitions p ON p.object_id = i.object_id AND p.index_id = i.index_id
  JOIN sys.allocation_units a ON a.container_id = p.partition_id
 WHERE t.name LIKE 'mart[_]%';
